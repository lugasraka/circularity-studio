function fmtEur(n: number, dp = 0): string {
  const v = n.toLocaleString("en-IE", { minimumFractionDigits: dp, maximumFractionDigits: dp });
  return `${n < 0 ? "−" : ""}€${v.replace("-", "")}`;
}

export function buildExecutiveSummary(state: StudioState): {
  headline: string;
  bullets: string[];
  tier1List: string;
  tier2List: string;
  coverage: string;
} {
  const { levers } = computeLevers(state);
  const sorted = sortLevers(levers);
  const s = summarize(levers);
  const inc = levers.filter((l) => l.included);
  const t1 = inc.filter((l) => l.tier === "T1");
  const t2 = inc.filter((l) => l.tier === "T2");
  const t3 = inc.filter((l) => l.tier === "T3");
  const top = sorted[0];
  const currency = (state.inputs.displayCurrency ?? "EUR") === "USD" ? "$" : "€";

  const coveragePct = s.includedKg > 0 ? "—" : "\u2014";
  const headline = top
    ? `${top.code} ${top.name} is the cheapest win at ${top.eurPerKg?.toFixed(1) ?? "—"} ${currency}/kg. Tier 1 pays for itself.`
    : "No levers screened in yet.";

  const bullets: string[] = [
    `${s.includedKg.toFixed(0)} kg virgin avoided per ${state.inputs.cohortSize.toLocaleString()} units (upper bound \u2014 levers overlap, never sum naively).`,
    `Net \u0394cost ${s.includedCostEur < 0 ? "\u2212" : ""}${currency}${Math.abs(s.includedCostEur).toLocaleString()} per cohort-year; Tier 1 captures ${currency}${Math.abs(s.tier1SavingsEur).toLocaleString()} (n=${s.tier1Count}).`,
    `CO\u2082e avoided: ${s.includedCo2eKg.toFixed(0)} kg. Revenue upside (green premium, share) deliberately excluded.`,
  ];

  const tier1List = t1.length ? t1.map((l) => `${l.code} ${l.name}`).join(" \u00b7 ") : "none";
  const tier2List = t2.length || t3.length ? [...t2, ...t3].map((l) => `${l.code} ${l.name}`).join(" \u00b7 ") : "none";

  return {
    headline,
    bullets,
    tier1List,
    tier2List,
    coverage: coveragePct,
  };
}

export function fmtForCurrency(valueEur: number, currency: "EUR" | "USD", fx: number, dp = 0): string {
  const display = currency === "EUR" ? valueEur : valueEur / fx;
  const sym = currency === "EUR" ? "\u20ac" : "$";
  const formatted = Math.abs(display).toLocaleString("en-IE", {
    minimumFractionDigits: dp,
    maximumFractionDigits: dp,
  });
  return `${display < 0 ? "\u2212" : ""}${sym}${formatted}`;
}

export function buildMarkdownReport(state: StudioState): string {
  const exec = buildExecutiveSummary(state);
  const { factors: f, levers } = computeLevers(state);
  const sorted = sortLevers(levers);
  const s = summarize(levers);
  const inc = levers.filter((l) => l.included);
  const exc = levers.filter((l) => !l.included);
  const i = state.inputs;

  const lines: string[] = [];
  lines.push(`# Circularity report — ${i.productName || "Untitled product"}`);
  lines.push("");
  lines.push(`Functional unit (US): ${i.usStatement || "—"}`);
  lines.push(`Cohort: ${i.cohortSize.toLocaleString()} units/year · Base year ${i.baseYear} · FX ${i.fxUsdEur} €/$ · CO₂e factor ${i.co2eFactor} kg CO₂e/kg`);
  lines.push("");
  lines.push("> Generated by Circularity Studio. Values are model outputs, not measurements; review against the assumptions in the relevant section before use.");
  lines.push("");
  lines.push("## Executive summary");
  lines.push("");
  lines.push(exec.headline);
  lines.push("");
  exec.bullets.forEach((b) => lines.push(`- ${b}`));
  lines.push("");
  lines.push(`Tier 1 (no-regret): ${exec.tier1List}`);
  lines.push(`Tier 2/3 (strategic/monitor): ${exec.tier2List}`);
  lines.push("");
  lines.push("## 1. Factor decomposition");
  lines.push("");
  lines.push("| Metric | Value |");
  lines.push("|---|---|");
  lines.push(`| P — product mass | ${f.mass.toFixed(2)} kg |`);
  lines.push(`| TM — total materials | ${f.tm.toFixed(2)} kg |`);
  lines.push(`| VM — virgin material | ${f.vm.toFixed(2)} kg |`);
  lines.push(`| Factor 1 — VM / TM | ${f.ratio1.toFixed(3)} |`);
  lines.push(`| Factor 2 — TM / P | ${f.ratio2.toFixed(3)} |`);
  lines.push(`| Factor 3 — P / US | ${f.ratio3.toFixed(3)} kg per unit-year |`);
  lines.push(`| **VM / US (headline)** | **${f.vmUsPerYear.toFixed(3)} kg per unit-year (${f.vmUsCohort.toFixed(1)} kg per cohort-year)** |`);
  lines.push(`| EBIT per unit | ${fmtEur(f.ebitUnit)} (${fmtEur(f.ebitCohort)} per cohort) |`);
  lines.push("");
  lines.push("## 2. Circularity Cost Curve (included levers, sorted ascending by €/kg)");
  lines.push("");
  lines.push("| # | Code | Lever | kg avoided /1,000 | €/1,000 | € per kg | kg CO₂e | Tier |");
  lines.push("|---|---|---|---|---|---|---|---|");
  sorted.forEach((l, idx) => {
    lines.push(
      `| ${idx + 1} | ${l.code} | ${l.name} | ${l.kg.toFixed(1)} | ${fmtEur(l.costEurPer1000)} | ${l.eurPerKg === null ? "n/a" : l.eurPerKg.toFixed(2)} | ${l.co2eKg.toFixed(0)} | ${l.tier} |`,
    );
  });
  lines.push("");
  lines.push(`Σ — kg avoided (upper bound): ${s.includedKg.toFixed(0)} · Σ Δcost: ${fmtEur(s.includedCostEur)} · Σ CO₂e: ${s.includedCo2eKg.toFixed(0)} kg`);
  lines.push("");
  lines.push("## 3. Decision");
  lines.push("");
  const tierLine = (t: "T1" | "T2" | "T3") =>
    inc.filter((l) => l.tier === t).map((l) => `${l.code} ${l.name}`).join(" · ") || "—";
  lines.push(`- Tier 1 — No-regret (${s.tier1Count}): ${tierLine("T1")}`);
  lines.push(`  → Savings: ${fmtEur(s.tier1SavingsEur)} per cohort-year`);
  lines.push(`- Tier 2 — Strategic (${s.tier2Count}): ${tierLine("T2")}`);
  lines.push(`  → Investment: ${fmtEur(s.tier2CostsEur)} per cohort-year`);
  lines.push(`- Tier 3 — Monitor (${s.tier3Count}): ${tierLine("T3")}`);
  lines.push("");
  if (exc.length) {
    lines.push("## 4. Screened out (with reasons)");
    lines.push("");
    for (const l of exc) {
      lines.push(`- ${l.code} ${l.name} — ${l.reason || "reason not recorded"}`);
    }
    lines.push("");
  }
  lines.push("## 5. Caveats");
  lines.push("");
  lines.push("- Σ totals are an upper bound: levers overlap (durability reduces returns; leasing reshapes 8a). Not additive.");
  lines.push("- Base curve = cost + EBIT impact only. Green premium and market-share growth are deliberately excluded.");
  lines.push("- Model kg for lever 1c, 6b and life-extension levers is parameter-driven; override with measured data where available.");
  lines.push("");
  return lines.join("\n");
}

export function downloadText(filename: string, content: string, mime = "text/markdown") {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function setCell(ws: any, addr: string, value: string | number) {
  ws[addr] = { ...(ws[addr] ?? {}), v: value, t: typeof value === "number" ? "n" : "s" };
}

/** Back-fill the Phase 2 Excel template with the current state and download it. */
export async function downloadBackFilledExcel(state: StudioState) {
  const XLSX = await import("xlsx");
  const res = await fetch("/circularity-cost-curve-template.xlsx");
  const buf = await res.arrayBuffer();
  const wb = XLSX.read(buf, { type: "array" });
  const i = state.inputs;

  const inputs = wb.Sheets["02 Inputs"];
  setCell(inputs, "B5", i.productName);
  setCell(inputs, "B6", i.usStatement);
  setCell(inputs, "B7", i.serviceLifeYears);
  setCell(inputs, "B8", i.utilizationHoursPerYear);
  setCell(inputs, "B9", i.cohortSize);
  setCell(inputs, "B10", i.baseYear);
  setCell(inputs, "B11", i.fxUsdEur);
  setCell(inputs, "B12", i.co2eFactor);
  setCell(inputs, "B13", i.virginShare);
  setCell(inputs, "B14", i.scrapRate);
  setCell(inputs, "B16", i.unitPrice);
  setCell(inputs, "B17", i.cogs);
  setCell(inputs, "B18", i.allocatedOverhead);
  i.bom.slice(0, 7).forEach((row, idx) => {
    const r = 22 + idx;
    setCell(inputs, `A${r}`, row.component);
    setCell(inputs, `B${r}`, row.family);
    setCell(inputs, `C${r}`, row.massKg);
    if (row.virginShare !== null) setCell(inputs, `D${r}`, row.virginShare);
  });

  const screen = wb.Sheets["04 Lever Screen"];
  LEVERS.forEach((def, idx) => {
    const r = 5 + idx;
    const g = state.gates[def.code] ?? [true, true, true];
    setCell(screen, `E${r}`, g[0] ? "Y" : "N");
    setCell(screen, `F${r}`, g[1] ? "Y" : "N");
    setCell(screen, `G${r}`, g[2] ? "Y" : "N");
  });

  const quant = wb.Sheets["05 Quantification"];
  LEVERS.forEach((def, idx) => {
    const r = 5 + idx;
    const o = state.overrides[def.code];
    if (o !== null && o !== undefined) setCell(quant, `F${r}`, o);
    setCell(quant, `H${r}`, state.costs[def.code] ?? 0);
    setCell(quant, `M${r}`, state.basis[def.code] ?? "");
    setCell(quant, `N${r}`, state.confidence[def.code] ?? "—");
  });
  const params = state.params;
  const paramKeys: (keyof typeof params)[] = [
    "scrap_pp", "recycled_uplift", "return_rate", "closed_loop_yield", "recyc_design_uplift",
    "reman_units", "reman_yield", "valorized_share", "mass_reduction", "leasing_uplift",
    "reuse_share", "refurb_share", "life_ext_repair", "life_ext_durability", "life_ext_care",
    "unsold_units",
  ];
  paramKeys.forEach((key, idx) => setCell(quant, `Q${5 + idx}`, params[key]));

  const safe = (i.productName || "product").replace(/[^a-z0-9-]+/gi, "-").toLowerCase();
  XLSX.writeFile(wb, `${safe}-circularity.xlsx`);
}
